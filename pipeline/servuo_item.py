#!/usr/bin/env python3
"""
servuo_item.py - generate a ServUO item class (C#) for a wearable that was added to the client.

    python servuo_item.py --name "Szata nekro" --graphic 0xFFDB --layer 22 --out <dir> [--class-name SzataNekro]
    python servuo_item.py --recipe recipe.json --out <dir> [--serv <ServUO folder>]     # every wearable item of a recipe

WHAT IT DOES
  Writes one <ClassName>.cs per item into --out (never into the server). The class follows the base classes of
  ServUO 5.8 (Scripts/Items/Equipment/Clothing: BaseOuterTorso, BaseCloak, BaseHat, ...): [Constructable] ctors with and
  without hue, the (Serial) ctor and a versioned Serialize/Deserialize. It sets only ItemID, Name and Weight - no
  combat statistics, no properties it cannot know.

  The layer decides the base class (numbers are UO's Layer enum, the same value as `layer` in the recipe / tiledata):
      3 Shoes -> BaseShoes     4 Pants -> BasePants     5 Shirt -> BaseShirt     6 Helm -> BaseHat
      12 Waist -> BaseWaist    17 MiddleTorso -> BaseMiddleTorso     20 Cloak -> BaseCloak
      22 OuterTorso -> BaseOuterTorso     23 OuterLegs -> BaseOuterLegs
      7, 10, 13, 19, 24 (gloves, neck, inner torso, arms, inner legs) -> BaseClothing with that Layer
  Weapons, shields and jewelry need their own base classes (BaseWeapon, ...) and are refused.

  With --serv the ServUO Scripts folder is scanned (time-boxed) for an existing class of the same name, because a
  duplicate type name stops the whole server from compiling.

NOT VERIFIED: the generated file has not been compiled against this shard's ServUO; do that (dotnet build) and test
the item in game. Copy it yourself into e.g. Scripts/Nelderim/Items/ - this tool never touches the server folder.
"""
from __future__ import annotations
import argparse, json, os, re, sys, time, unicodedata

# layer number -> (Layer enum name, ServUO base class, ctor kind)
#   kind "item"  : base(itemID, hue)            (BaseOuterTorso, BaseCloak, ...)
#   kind "layer" : base(itemID, Layer.X, hue)   (BaseClothing)
LAYERS = {
    3: ("Shoes", "BaseShoes", "item"),
    4: ("Pants", "BasePants", "item"),
    5: ("Shirt", "BaseShirt", "item"),
    6: ("Helm", "BaseHat", "item"),
    7: ("Gloves", "BaseClothing", "layer"),
    10: ("Neck", "BaseClothing", "layer"),
    12: ("Waist", "BaseWaist", "item"),
    13: ("InnerTorso", "BaseClothing", "layer"),
    17: ("MiddleTorso", "BaseMiddleTorso", "item"),
    19: ("Arms", "BaseClothing", "layer"),
    20: ("Cloak", "BaseCloak", "item"),
    22: ("OuterTorso", "BaseOuterTorso", "item"),
    23: ("OuterLegs", "BaseOuterLegs", "item"),
    24: ("InnerLegs", "BaseClothing", "layer"),
}
NAMES = {v[0].lower(): k for k, v in LAYERS.items()}
NAMES.update({"robe": 22, "torso": 22, "outertorso": 22, "innertorso": 13})

_FOLD = str.maketrans({"ł": "l", "Ł": "L", "ø": "o", "Ø": "O", "đ": "d", "Đ": "D"})
RESERVED = {"abstract", "class", "namespace", "object", "string", "int", "void", "new", "static", "public", "item"}


def parse_int(v):
    if isinstance(v, int):
        return v
    s = str(v).strip()
    return int(s, 16) if s.lower().startswith("0x") else int(s)


def parse_layer(v):
    s = str(v).strip().lower()
    if s in NAMES:
        return NAMES[s]
    n = parse_int(s)
    if n not in LAYERS:
        raise ValueError(f"warstwa {n} nie jest obsługiwana (ubrania: {sorted(LAYERS)}); broń i biżuteria mają inne klasy bazowe")
    return n


def class_name_from(name):
    folded = unicodedata.normalize("NFKD", name.translate(_FOLD))
    ascii_ = "".join(c for c in folded if not unicodedata.combining(c))
    words = re.findall(r"[A-Za-z0-9]+", ascii_)
    cn = "".join(w[:1].upper() + w[1:] for w in words)
    if not cn or not cn[0].isalpha():
        cn = "Item" + cn
    if cn.lower() in RESERVED:
        cn += "Item"
    return cn


def cs_string(s):
    """valid C# string literal; non-ASCII as \\uXXXX so the source encoding never matters."""
    return json.dumps(s, ensure_ascii=True)


def render(name, class_name, graphic, layer, weight=1.0, hue=0):
    lname, base, kind = LAYERS[layer]
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", class_name):
        raise ValueError(f"niepoprawna nazwa klasy: {class_name!r}")
    if not 0 < graphic <= 0xFFFF:
        raise ValueError(f"ID przedmiotu poza zakresem: {graphic}")
    base_call = f"base(0x{graphic:04X}, hue)" if kind == "item" else f"base(0x{graphic:04X}, Layer.{lname}, hue)"
    w = f"{weight:g}"
    if "." not in w:
        w += ".0"
    return f'''// Generated by Nelderim Lab (pipeline/servuo_item.py). Not compiled or tested against this shard yet.
// Copy to e.g. Scripts/Nelderim/Items/, run `dotnet build`, restart the server. Layer {layer} = {lname}.
using System;

namespace Server.Items
{{
    public class {class_name} : {base}
    {{
        [Constructable]
        public {class_name}()
            : this(0)
        {{
        }}

        [Constructable]
        public {class_name}(int hue)
            : {base_call}
        {{
            Name = {cs_string(name)};
            Weight = {w};
        }}

        public {class_name}(Serial serial)
            : base(serial)
        {{
        }}

        public override void Serialize(GenericWriter writer)
        {{
            base.Serialize(writer);
            writer.Write(0); // version
        }}

        public override void Deserialize(GenericReader reader)
        {{
            base.Deserialize(reader);
            int version = reader.ReadInt();
        }}
    }}
}}
'''


def find_existing(serv, class_name, budget_s=25.0):
    """-> (path or None, files scanned, finished). Looks for `class <name>` in ServUO's Scripts (time-boxed)."""
    scripts = os.path.join(serv, "Scripts")
    if not os.path.isdir(scripts):
        return None, 0, True
    pat = re.compile(r"\b(class|struct|enum|interface)\s+" + re.escape(class_name) + r"\b")
    t0, n = time.time(), 0
    for root, _dirs, files in os.walk(scripts):
        for f in files:
            if not f.endswith(".cs"):
                continue
            if time.time() - t0 > budget_s:
                return None, n, False
            n += 1
            try:
                with open(os.path.join(root, f), encoding="utf-8", errors="replace") as fh:
                    if pat.search(fh.read()):
                        return os.path.join(root, f), n, True
            except OSError:
                continue
    return None, n, True


def items_from_recipe(path):
    rec = json.load(open(path, encoding="utf-8"))
    out = []
    for it in rec.get("items", []):
        if it.get("vd") or not it.get("item_id"):
            continue
        out.append({"name": it.get("tile_name") or it.get("name") or "", "graphic": parse_int(it["item_id"]),
                    "layer": it.get("layer"), "class_name": it.get("class_name") or ""})
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description="klasa C# (ServUO) dla przedmiotu do noszenia")
    ap.add_argument("--recipe")
    ap.add_argument("--name")
    ap.add_argument("--graphic")
    ap.add_argument("--layer", help="numer warstwy (22) albo nazwa (robe, cloak, helm ...)")
    ap.add_argument("--class-name", default="")
    ap.add_argument("--weight", type=float, default=1.0)
    ap.add_argument("--out", required=True)
    ap.add_argument("--serv", default="", help="folder ServUO - sprawdź, czy taka klasa już istnieje")
    ap.add_argument("--overwrite", action="store_true")
    ap.add_argument("--json", action="store_true")
    a = ap.parse_args(argv)

    todo = []
    if a.recipe:
        todo = items_from_recipe(a.recipe)
        if not todo:
            print("[BŁĄD  ] w recepturze nie ma przedmiotów do noszenia (z item_id)")
    else:
        if not (a.name and a.graphic and a.layer is not None):
            ap.error("podaj --recipe albo --name, --graphic i --layer")
        todo = [{"name": a.name, "graphic": parse_int(a.graphic), "layer": a.layer, "class_name": a.class_name}]

    results, rc = [], 0
    os.makedirs(a.out, exist_ok=True)
    for it in todo:
        r = {"name": it["name"], "graphic": it["graphic"]}
        try:
            if it["layer"] is None or str(it["layer"]).strip() == "":
                raise ValueError("brak warstwy (layer) - wpisz ją w recepturze")
            layer = parse_layer(it["layer"])
            cn = it["class_name"] or class_name_from(it["name"])
            r.update(class_name=cn, layer=layer, base=LAYERS[layer][1])
            if a.serv:
                hit, n, done = find_existing(a.serv, cn)
                if hit:
                    raise ValueError(f"klasa {cn} już istnieje w ServUO: {hit} (zmień --class-name)")
                if not done:
                    r["warning"] = f"sprawdzono tylko {n} plików .cs (limit czasu) - kolizji nazwy nie wykluczam"
            path = os.path.join(a.out, cn + ".cs")
            if os.path.exists(path) and not a.overwrite:
                raise ValueError(f"plik już istnieje: {path} (użyj --overwrite)")
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(render(it["name"], cn, it["graphic"], layer, a.weight))
            r["file"] = path
            print(f"[KLASA ] {cn}.cs  (0x{it['graphic']:04X}, warstwa {layer} -> {LAYERS[layer][1]}) {path}")
            if r.get("warning"):
                print("[WARN  ] " + r["warning"])
        except (ValueError, KeyError) as e:
            r["error"] = str(e)
            print(f"[BŁĄD  ] {it.get('name') or '?'}: {e}")
            rc = 1
        results.append(r)
    if a.json:
        print("RESULT_JSON " + json.dumps({"items": results}, ensure_ascii=False))
    return rc


if __name__ == "__main__":
    sys.exit(main())
